import os; _R=os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),"..")); import sys; sys.path.insert(0,_R)
from common import *
L=lambda s:3/(s*(1+s/2)*(1+s/10))
# ---- geometria de 1+L
Lp=2*np.exp(-1j*np.radians(120))
fig,ax=plt.subplots(figsize=(5.6,4.4))
ax.set_aspect("equal"); style(ax)
th=np.linspace(0,2*np.pi,400); ax.plot(np.cos(th),np.sin(th),color=INK2,lw=0.8,ls="--")
ax.axhline(0,color=INK2,lw=1); ax.axvline(0,color=INK2,lw=1)
ar=dict(arrowstyle="-|>",lw=2,mutation_scale=14,shrinkA=0,shrinkB=0)
ax.annotate("",xy=(Lp.real,Lp.imag),xytext=(0,0),arrowprops=dict(color=BLUE,**ar))
ax.annotate("",xy=(Lp.real,Lp.imag),xytext=(-1,0),arrowprops=dict(color=ORANGE,**ar))
ax.plot(-1,0,"o",color=INK,ms=8); ax.text(-1.0,0.2,"$-1$",ha="center",fontsize=12)
ax.plot(Lp.real,Lp.imag,"o",color=INK,ms=8,mec="white"); ax.text(Lp.real-0.08,Lp.imag-0.28,"$L(j\\omega)$",ha="right",fontsize=12)
ax.text(-0.42,-0.75,"$|L|=2$",color=BLUE,fontsize=11,ha="right")
ax.text(-1.08,-0.85,"$|1+L|=1{,}73$",color=ORANGE,fontsize=11,ha="right")
ax.text(1.0,-0.2,"círculo $|L|=1$",color=INK2,fontsize=9.5)
ax.set_xlim(-2.6,1.6); ax.set_ylim(-2.3,1.3); ax.set_xlabel("parte real"); ax.set_ylabel("parte imaginaria")
fig.tight_layout(); fig.savefig("fig/geometria.png",dpi=200,bbox_inches="tight"); plt.close(fig)
# ---- Nyquist + |T|
w=np.logspace(-1.5,2,4000); z=L(1j*w); T=z/(1+z)
mk=[1,2,3,5]; cols=[BLUE,GREEN,PURPLE,"#b8860b"]
fig,(a,b)=plt.subplots(1,2,figsize=(11.5,4.1))
style(a); style(b)
a.plot(z.real,z.imag,color=INK,lw=2); a.axhline(0,color=INK2,lw=1); a.axvline(0,color=INK2,lw=1)
a.plot(-1,0,"o",color=ORANGE,ms=9,mec="white"); a.text(-0.9,0.25,"$-1$",fontsize=12)
b.plot(w,db(T),color=INK,lw=2); b.axhline(0,color=INK2,lw=1); b.set_xscale("log")
for wv,c in zip(mk,cols):
    zz=L(1j*wv); tt=zz/(1+zz)
    a.plot(zz.real,zz.imag,"o",color=c,ms=8,mec="white"); a.annotate(f"$\\omega={wv:g}$".replace(".",","),(zz.real,zz.imag),xytext=(8,-14) if wv>=3 else (-52,-4),textcoords="offset points",fontsize=10,color=c)
    b.plot(wv,db(tt),"o",color=c,ms=8,mec="white")
    print(wv,zz,abs(zz),np.degrees(np.angle(zz)),db(zz),abs(tt),db(tt),np.degrees(np.angle(tt)))
a.set_xlim(-2.2,0.6); a.set_ylim(-3.0,0.6); a.set_xlabel("parte real de $L(j\\omega)$"); a.set_ylabel("parte imaginaria")
a.set_title("$L(j\\omega)$ en el plano complejo",loc="left",fontsize=11.5)
b.set_xlabel("$\\omega$ (rad/s)"); b.set_ylabel("$|T(j\\omega)|$ (dB)"); b.set_title("Lo que sale del lazo cerrado",loc="left",fontsize=11.5)
b.set_ylim(-35,8)
i=np.argmax(db(T)); b.annotate(f"pico {db(T)[i]:.1f} dB".replace(".",","),(w[i],db(T)[i]),xytext=(0.04,4),fontsize=10,arrowprops=dict(arrowstyle="-",color=INK2,lw=1))
z2=L(2j); a.annotate("",xy=(z2.real,z2.imag),xytext=(-1,0),arrowprops=dict(arrowstyle="-|>",color=ORANGE,lw=1.8,shrinkA=0,shrinkB=3)); a.text(-2.1,-0.95,"$|1+L|$ en $\\omega=2$\nes corto: $|T|$ sube",fontsize=10,color=ORANGE)
fig.tight_layout(); fig.savefig("fig/nyquist_T.png",dpi=200,bbox_inches="tight"); plt.close(fig)
print("peak",db(T).max(),w[np.argmax(db(T))])
